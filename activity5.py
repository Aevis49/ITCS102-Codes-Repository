#Operators = Symbols 
#+ - addition
#- - subtraction
#* - multiplication
#/ - division
#// - floor div
#** - exponential
#% - modulus

A = 94
B = 4
sum = A + B
sub = A - B
mul = A*B




print("The sum of ",A," and ",B," is ",sum)
print("The subtraction of ",A," and ",B," is", sub)
print("The multiplication of ",A," and ",B," is ", mul)
print("The division of ",A," and ",B," is ", 94/4)
print("The floor division of ",A," and ",B," is ", 94//4) #IT REMOVES THE REMAINDER, AMAZING
print("The exponetial multiplication of ",A," and ",B," is ", 94**4)
print("The modulus of ",A," and ",B," is ", 94%4)
